def graph_statistics(graph: Graph) -> Dict[str, Any]:
    """NetworkX metrics over the merged graph, for a structural sanity check."""
    try:
        import networkx as nx
    except ImportError:
        return {"error": "networkx unavailable"}

    dg = nx.DiGraph()
    for s, p, o in graph:
        if isinstance(s, URIRef) and isinstance(o, URIRef):
            dg.add_edge(str(s), str(o), predicate=str(p))

    degrees = sorted(dg.degree, key=lambda kv: -kv[1])[:15]
    undirected = dg.to_undirected()
    components = list(nx.connected_components(undirected)) if undirected.number_of_nodes() else []

    return {
        "nodes": dg.number_of_nodes(),
        "edges": dg.number_of_edges(),
        "connected_components": len(components),
        "largest_component_size": max((len(c) for c in components), default=0),
        "isolated_nodes": len(list(nx.isolates(dg))),
        "most_connected": [{"node": n, "degree": d} for n, d in degrees],
        "note": (
            "A single dominant component is expected: the TBox, the claims and the "
            "assessments are meant to be reachable from one another. Isolated nodes "
            "indicate vocabulary that nothing yet uses."
        ),
    }


def run(config: Dict[str, Any]) -> Dict[str, Any]:
    build_dir = REPO_ROOT / config["paths"]["build_dir"]
    out_dir = REPO_ROOT / config["paths"]["outputs_dir"]
    full = build_dir / "mdkg-full.ttl"
    if not full.exists():
        raise SystemExit(f"{full} missing; run scripts/build_ontology.py first")

    graph = Graph()
    graph.parse(full, format="turtle")
    LOG.info("loaded %d triples", len(graph))

    written = {
        "core_ontology_map.mmd": write(out_dir / "core_ontology_map.mmd", core_map(graph)),
        "mechanical_design_map.mmd": write(out_dir / "mechanical_design_map.mmd", mechanical_map(graph)),
        "machine_element_map.mmd": write(out_dir / "machine_element_map.mmd", machine_element_map(graph)),
        "evidence_pipeline_map.mmd": write(out_dir / "evidence_pipeline_map.mmd", evidence_pipeline_map(graph)),
        "substitution_model_map.mmd": write(out_dir / "substitution_model_map.mmd", substitution_model_map(graph)),
    }
    stats = graph_statistics(graph)
    (out_dir / "graph_statistics.json").write_text(
        json.dumps(stats, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return {"diagrams": written, "graph_statistics": {k: v for k, v in stats.items() if k != "most_connected"}}


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--verbose", "-v", action="store_true")
    args = parser.parse_args(argv)
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)-7s %(name)s: %(message)s",
    )
    with args.config.open(encoding="utf-8") as fh:
        config = yaml.safe_load(fh)
    print(json.dumps(run(config), indent=2, sort_keys=True))
    return 0


