#!/usr/bin/env python3
"""Generate Mermaid ontology maps and a graph-statistics report.

Every diagram is derived from the built RDF, not hand-drawn, so a map can never
drift out of step with the ontology it depicts.  Where a diagram would become
unreadable if fully expanded (the machine-element taxonomy has ~90 leaf types),
the generator prunes deliberately and states in the diagram itself what it
pruned, rather than silently showing a partial picture.

Outputs, into ``outputs/``:

``core_ontology_map.mmd``        Level 1 general design core
``mechanical_design_map.mmd``    Level 2 mechanical extension, incl. FBS wiring
``machine_element_map.mmd``      Level 3 machine-element families
``evidence_pipeline_map.mmd``    claim and evidence flow, with the review ladder
``substitution_model_map.mmd``   the reified substitution assessment
``graph_statistics.json``        NetworkX metrics over the merged graph
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Sequence, Set, Tuple

import yaml
from rdflib import Graph, Namespace, URIRef
from rdflib.namespace import OWL, RDF, RDFS, SKOS

LOG = logging.getLogger("generate_maps")
REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CONFIG = REPO_ROOT / "config" / "config.yaml"

MDCORE = Namespace("https://w3id.org/mdkg/core#")
MECH = Namespace("https://w3id.org/mdkg/mechanical-design#")
MELEM = Namespace("https://w3id.org/mdkg/machine-elements#")
EV = Namespace("https://w3id.org/mdkg/evidence#")

NS_PREFIX = {
    str(MDCORE): "mdcore", str(MECH): "mech", str(MELEM): "melem", str(EV): "ev",
}


def local_name(iri: Any) -> str:
    """Return the local part of an IRI."""
    text = str(iri)
    return text.rsplit("#", 1)[-1] if "#" in text else text.rsplit("/", 1)[-1]


def node_id(iri: Any) -> str:
    """A Mermaid-safe node identifier."""
    for ns, prefix in NS_PREFIX.items():
        if str(iri).startswith(ns):
            return f"{prefix}_{local_name(iri)}"
    return local_name(iri).replace("-", "_")


def label_of(graph: Graph, iri: URIRef) -> str:
    """Human label for a node, falling back to its local name."""
    lbl = graph.value(iri, RDFS.label)
    text = str(lbl) if lbl else local_name(iri)
    return text.replace('"', "'")


def in_ns(iri: Any, ns: Namespace) -> bool:
    return str(iri).startswith(str(ns))


def subclass_edges(graph: Graph, ns: Namespace) -> List[Tuple[URIRef, URIRef]]:
    """Named subclass edges whose child lives in *ns*."""
    edges = []
    for child, parent in graph.subject_objects(RDFS.subClassOf):
        if not isinstance(child, URIRef) or not isinstance(parent, URIRef):
            continue
        if in_ns(child, ns):
            edges.append((child, parent))
    return edges


def write(path: Path, lines: Iterable[str]) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines) + "\n"
    path.write_text(text, encoding="utf-8")
    LOG.info("wrote %s (%d lines)", path, text.count("\n"))
    return text.count("\n")


